#!/usr/bin/env node
// Builds the demo home page and the nginx config that serves it with every demo behind one port:
//
//   /              this home page: a card per app, its start pages and its sample accounts
//   /issues/ …     each demo's fieldtec-web (demo/app.mjs: port, basePath), with the prefix stripped
//
// The accounts, passwords and start pages come from each app's buildDemo(), the same function its
// seed uses, so the page always matches the database. Writes portal/dist/ (index.html, _home/,
// nginx.conf). See portal/README.md.

import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { renderPage } from './page.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const dist = path.join(here, 'dist');
const port = Number(process.env.PORTAL_PORT ?? 8080);


// ------------------------------------------------------------------------------------- the apps
const apps = [];
for (const dir of readdirSync(root).sort()) {
  const appFile = path.join(root, dir, 'demo/app.mjs');
  if (!existsSync(appFile)) continue;
  const { app } = await import(pathToFileURL(appFile).href);
  if (!app.basePath || !app.portal) continue;
  const { buildDemo } = await import(pathToFileURL(path.join(app.appRoot, app.buildModule)).href);
  const demo = buildDemo({ now: new Date(), urlRoot: `/${app.basePath}` });
  const backgrounds = path.join(app.appRoot, 'demo/backgrounds');
  const picture = existsSync(backgrounds) ? readdirSync(backgrounds).sort().find((f) => /^login-.*\.(jpe?g|png|webp)$/i.test(f)) : undefined;
  apps.push({ ...app, people: demo.people, password: demo.password, urls: demo.urls, picture: picture && path.join(backgrounds, picture) });
}
apps.sort((a, b) => a.port - b.port);
if (!apps.length) throw new Error(`No demo/app.mjs with a basePath found under ${root}.`);

// Only the page's own files are replaced: dist/ also holds a running nginx's pid file and logs.
rmSync(path.join(dist, '_home'), { recursive: true, force: true });
mkdirSync(path.join(dist, '_home'), { recursive: true });
mkdirSync(path.join(dist, 'logs'), { recursive: true });
mkdirSync(path.join(dist, 'tmp'), { recursive: true });
for (const app of apps) {
  if (!app.picture) continue;
  app.image = `_home/${app.basePath}${path.extname(app.picture)}`;
  copyFileSync(app.picture, path.join(dist, app.image));
}

// ------------------------------------------------------------------------------------ home page
// The Storybook of every element (storybook/: pnpm build), served at /storybook/ when it is built.
const storybookDist = path.join(root, 'storybook/dist');
const storybook = existsSync(path.join(storybookDist, 'index.html'));
writeFileSync(path.join(dist, 'index.html'), renderPage(apps, { port, storybook }));

// ---------------------------------------------------------------------------------------- nginx
// The five servers run at / on one fieldtec-web checkout and share its server/public/index.html, so
// they can't each run under their own urlBase.path. Instead nginx strips /<app> before proxying and
// sets the page's <base href> to /<app>/; fieldtec-web's client takes its API, socket.io and
// storage paths from that tag. The session cookie is scoped to /<app>/, so each app keeps its own
// sign-in, and redirects to /… are put back under /<app>/.
//
// Links
// stored in the demo data and in the Solid elements are root-relative (/form/<id>, /search/…); the
// app pages resolve them through Angular's router, but a link opened in a new tab or copied lands
// on the root. Those are sent back under the app they came from: the Referer's first path segment,
// or else the demo_app cookie each app's responses set.
const names = apps.map((a) => a.basePath).join('|');
const nginx = `# Generated by portal/build.mjs. Run with: portal/run.sh up
worker_processes 1;
pid ${dist}/nginx.pid;
error_log ${dist}/logs/error.log warn;

events { worker_connections 1024; }

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log ${dist}/logs/access.log;
    sendfile on;
    keepalive_timeout 65;

    client_body_temp_path ${dist}/tmp/body;
    proxy_temp_path ${dist}/tmp/proxy;
    fastcgi_temp_path ${dist}/tmp/fastcgi;
    uwsgi_temp_path ${dist}/tmp/uwsgi;
    scgi_temp_path ${dist}/tmp/scgi;

    map $http_upgrade $connection_upgrade { default upgrade; '' close; }
    map $http_referer $referer_app { "~^https?://[^/]+/(${names})(/|$)" $1; default ""; }
    map $cookie_demo_app $cookie_app { "~^(${names})$" $1; default ""; }
    map "$referer_app:$cookie_app" $stray_app { "~^([^:]+):" $1; "~^:(.+)$" $1; default ""; }
    map $http_x_forwarded_proto $forwarded_proto { default $http_x_forwarded_proto; "" $scheme; }

    server {
        listen ${port};
        server_name _;
        # Relative Location headers: behind Coder's https proxy nginx only sees http.
        absolute_redirect off;

        client_max_body_size 100M;
        proxy_http_version 1.1;
        proxy_connect_timeout 60s;
        proxy_send_timeout 600s;
        proxy_read_timeout 600s;
        proxy_buffer_size 16k;
        proxy_buffers 8 256k;
        proxy_busy_buffers_size 512k;
        proxy_set_header Host $http_host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $forwarded_proto;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;

        location = / {
            root ${dist};
            try_files /index.html =404;
            add_header Cache-Control "no-cache";
        }
        location /_home/ {
            alias ${dist}/_home/;
            expires 1h;
        }

        # The Storybook's static build (storybook/: pnpm build). Its links are relative.
        location = /storybook { return 301 /storybook/; }
        location /storybook/ {
            alias ${storybookDist}/;
            add_header Cache-Control "no-cache";
        }
${apps.map((a) => `
        # ${a.portal.name}: ${a.config}, port ${a.port}
        location = /${a.basePath} { return 301 /${a.basePath}/; }
        location /${a.basePath}/ {
            proxy_pass http://127.0.0.1:${a.port}/;
            proxy_set_header Accept-Encoding "";
            sub_filter '<base href="/">' '<base href="/${a.basePath}/">';
            sub_filter_once on;
            proxy_redirect ~^https?://[^/]+/(.*)$ /${a.basePath}/$1;
            proxy_redirect / /${a.basePath}/;
            proxy_cookie_path / /${a.basePath}/;
            add_header Set-Cookie "demo_app=${a.basePath}; Path=/; SameSite=Lax";
        }`).join('\n')}

        # A root-relative link (/form/<id>, /api/…) that left its app: back under the app it came from.
        location / {
            if ($stray_app) { return 307 /$stray_app$request_uri; }
            return 302 /;
        }
    }
}
`;
writeFileSync(path.join(dist, 'nginx.conf'), nginx);

console.log(`Wrote ${path.relative(root, dist)}/index.html and nginx.conf (port ${port}):`);
for (const a of apps) console.log(`  /${a.basePath.padEnd(12)} -> 127.0.0.1:${a.port}  ${a.portal.name}, ${a.people.length} accounts`);
console.log(`  /storybook/    -> storybook/dist ${storybook ? '' : '(not built yet: cd storybook && pnpm install && pnpm build)'}`);
